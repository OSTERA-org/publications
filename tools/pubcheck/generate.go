// pageFile is the generated landing page in each document directory and
// each version directory. Jekyll turns it into index.html, so it is what
// a visitor sees at https://pub.ostera.org/<shortname>/ and at
// https://pub.ostera.org/<shortname>/v<version>/.
const pageFile = "index.md"

// catalogFile is the machine readable list of every published document,
// served at https://pub.ostera.org/catalog.json.
const catalogFile = docsDir + "/catalog.json"

const generatedNote = "<!-- Generated by pubcheck from registry.yaml, metadata.yaml, and review.yaml. Do not edit by hand. -->"

// site is everything the pages are generated from.
type site struct {
	reg     *Registry
	docs    []Document
	reviews []ReviewDir
}

// loadSite reads registry.yaml, every metadata.yaml, and every
// review.yaml. It returns nil when registry.yaml cannot be read.
func loadSite(root string, p *Problems) *site {
	reg := loadRegistry(root, p)
	docs := loadDocuments(root, p)
	reviews := loadReviews(root, p)
	if reg == nil {
		return nil
	}
	return &site{reg: reg, docs: docs, reviews: reviews}
}

// A section is a generated part of a page that is otherwise written by
// hand. Only the text between the two markers is replaced.
type section struct {
	path string // relative to the repository root
	name string // used in the markers
	body func(s *site) string
}

var sections = []section{
	{docsDir + "/index.md", "documents", homeSection},
	{docsDir + "/about.md", "document-types", typesSection},
	{reviewsIndex, "reviews", reviewsSection},
}

// beginMarker is the line that starts a generated section. Its wording
// must never change, because the hand written pages contain it.
func beginMarker(name string) string {
	return "<!-- BEGIN GENERATED " + name + ": pubcheck writes this section from registry.yaml and metadata.yaml; do not edit by hand -->"
}

func endMarker(name string) string { return "<!-- END GENERATED " + name + " -->" }

// generatedFiles returns every fully generated file, keyed by its path
// relative to the repository root.
func generatedFiles(s *site) (map[string][]byte, error) {
	out := map[string][]byte{}
	for _, d := range s.docs {
		out[d.Dir+"/"+pageFile] = []byte(documentPage(s, d))
		for i := range d.Meta.Versions {
			v := &d.Meta.Versions[i]
			out[d.Dir+"/"+versionDir(v.Version)+"/"+pageFile] = []byte(versionPage(s.reg, d, v))
		}
	}
	for _, short := range reviewShortnames(s) {
		out[reviewsIndexDir(short)+"/"+pageFile] = []byte(workItemPage(s, short))
	}
	for _, rv := range s.reviews {
		out[rv.Dir+"/"+pageFile] = []byte(reviewPage(s, rv))
	}
	cat, err := catalogJSON(s.reg, s.docs)
	if err != nil {
		return nil, err
	}
	out[catalogFile] = cat
	return out, nil
}

func generate(root string) (*Problems, error) {
	p := &Problems{}
	st := loadSite(root, p)
	if st == nil {
		return p, nil
	}
	// The pages are written from registry.yaml, metadata.yaml, and
	// review.yaml, so those must be correct first. The files on disk are
	// checked by validate.
	checkRegistry(st.reg, p)
	checkDocuments(root, st.reg, st.docs, false, p)
	checkReviews(root, st, false, p)
	if p.Len() > 0 {
		return p, nil
	}
	// Check the hand written pages first, so nothing is written when a
	// marker is missing.
	updated := map[string]string{}
	for _, s := range sections {
		data, err := os.ReadFile(filepath.Join(root, s.path))
		if err != nil {
			p.Addf(s.path, "cannot read: %v", err)
			continue
		}
		text, ok := withSection(string(data), s.name, s.body(st))
		if !ok {
			p.Addf(s.path, "is missing the markers for the generated %s section; add these two lines where the section belongs:\n  %s\n  %s", s.name, beginMarker(s.name), endMarker(s.name))
			continue
		}
		updated[s.path] = text
	}
	if p.Len() > 0 {
		return p, nil
	}
	files, err := generatedFiles(st)
	if err != nil {
		return nil, err
	}
	for rel, text := range updated {
		files[rel] = []byte(text)
	}
	for rel, data := range files {
		abs := filepath.Join(root, rel)
		if err := os.MkdirAll(filepath.Dir(abs), 0o755); err != nil {
			return nil, err
		}
		if err := os.WriteFile(abs, data, 0o644); err != nil {
			return nil, err
		}
	}
	return p, nil
}

func checkGenerated(root string, st *site, p *Problems) {
	files, err := generatedFiles(st)
	if err != nil {
		p.Addf(catalogFile, "cannot generate: %v", err)
		return
	}
	for rel, want := range files {
		got, err := os.ReadFile(filepath.Join(root, rel))
		if err != nil || string(got) != string(want) {
			p.Addf(rel, "is missing or out of date; run pubcheck generate")
		}
	}
	for _, s := range sections {
		got, err := os.ReadFile(filepath.Join(root, s.path))
		if err != nil {
			p.Addf(s.path, "is missing")
			continue
		}
		text, ok := withSection(string(got), s.name, s.body(st))
		switch {
		case !ok:
			p.Addf(s.path, "is missing the markers for the generated %s section", s.name)
		case text != string(got):
			p.Addf(s.path, "the generated %s section is out of date; run pubcheck generate", s.name)
		}
	}
}

// withSection replaces the text between the markers for name. It reports
// false when the markers are missing or out of order.
func withSection(page, name, body string) (string, bool) {
	begin, end := beginMarker(name), endMarker(name)
	b := strings.Index(page, begin)
	e := strings.Index(page, end)
	if b < 0 || e < b {
		return page, false
	}
	// Blank lines around the body keep Markdown from joining it to the
	// marker comments.
	return page[:b] + begin + "\n\n" + strings.TrimRight(body, "\n") + "\n\n" + end + page[e+len(end):], true
}

// ---------- shared helpers ----------

func latestPublished(m *Metadata) *Version {
	for i := len(m.Versions) - 1; i >= 0; i-- {
		if m.Versions[i].Status == "published" {
			return &m.Versions[i]
		}
	}
	return nil
}

// currentType is the type of the latest published version, or of the
// newest version when none is still published.
func currentType(m *Metadata) string {
	if v := latestPublished(m); v != nil {
		return v.Type
	}
	return m.Versions[len(m.Versions)-1].Type
}

// newerPublished returns the latest published version that is newer than
// v, or nil.
func newerPublished(m *Metadata, v *Version) *Version {
	l := latestPublished(m)
	if l == nil || l == v {
		return nil
	}
	for i := range m.Versions {
		if &m.Versions[i] == v {
			for j := i + 1; j < len(m.Versions); j++ {
				if &m.Versions[j] == l {
					return l
				}
			}
		}
	}
	return nil
}

func joinList(items []string) string {
	switch len(items) {
	case 0:
		return ""
	case 1:
		return items[0]
	case 2:
		return items[0] + " and " + items[1]
	}
	return strings.Join(items[:len(items)-1], ", ") + ", and " + items[len(items)-1]
}

func titleCase(s string) string {
	if s == "" {
		return s
	}
	return strings.ToUpper(s[:1]) + s[1:]
}

var languageNames = map[string]string{
	"de": "German", "en": "English", "es": "Spanish", "fr": "French",
	"it": "Italian", "ja": "Japanese", "ko": "Korean", "nl": "Dutch",
	"pt": "Portuguese", "zh": "Chinese",
}

var formatNames = map[string]string{
	"pdf": "PDF", "md": "Markdown", "html": "HTML", "txt": "Text",
	"docx": "Word", "epub": "EPUB",
}

func fileLabel(lang, format string) string {
	l, ok := languageNames[lang]
	if !ok {
		l = lang
	}
	f, ok := formatNames[format]
	if !ok {
		f = strings.ToUpper(format)
	}
	return l + " " + f
}

// patentText describes, for readers, whether a type carries the patent
// licensing obligations of the IPR and Copyright Policy.
var patentText = map[string]string{
	"standards":      "Yes",
	"informative":    "No",
	"parent":         "Same as the document it supplements",
	"organizational": "Not applicable",
}

func typeName(r *Registry, code string) string {
	if t, ok := r.Types[code]; ok {
		return fmt.Sprintf("%s (%s)", t.Name, code)
	}
	return code
}

// orderedTypes lists the type codes in the order they appear in the
// ranges, technical documents first.
func orderedTypes(r *Registry) []string {
	names := sortedKeys(r.Ranges)
	sort.SliceStable(names, func(i, j int) bool { return r.Ranges[names[i]].First > r.Ranges[names[j]].First })
	var codes []string
	for _, n := range names {
		codes = append(codes, r.Ranges[n].Types...)
	}
	return codes
}

func people(list []Person) string {
	var s []string
	for _, x := range list {
		s = append(s, fmt.Sprintf("%s (%s)", x.Name, x.Affiliation))
	}
	return joinList(s)
}

// cell makes text safe inside a Markdown table cell.
func cell(s string) string { return strings.ReplaceAll(s, "|", `\|`) }

// quoted returns s as a quoted YAML string, for front matter.
func quoted(s string) string {
	b, _ := json.Marshal(s)
	return string(b)
}

func frontMatter(title, lead string) string {
	return "---\nlayout: page\ntitle: " + quoted(title) + "\nlead: " + quoted(lead) + "\n---\n" + generatedNote + "\n\n"
}

// path returns the site path of a document folder or of a file under it.
func path(m *Metadata, parts ...string) string {
	return "/" + strings.Join(append([]string{m.Shortname}, parts...), "/")
}

func versionLink(m *Metadata, v *Version) string {
	return fmt.Sprintf("[Version %s](%s/)", v.Version, path(m, versionDir(v.Version)))
}

func workingGroupLink(r *Registry, m *Metadata) string {
	if m.WorkingGroup == "" {
		return ""
	}
	name := m.WorkingGroup
	if wg, ok := r.WorkingGroups[m.WorkingGroup]; ok {
		name = wg.Name
	}
	return fmt.Sprintf("[%s](https://wg.ostera.org/%s/)", name, m.WorkingGroup)
}

func githubLink(rel string) string {
	return fmt.Sprintf("[Browse these files on GitHub](%s/tree/main/%s)", repoURL, rel)
}

// ---------- document landing page ----------

func documentPage(s *site, d Document) string {
	r := s.reg
	m := d.Meta
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }

	w("%s", frontMatter(m.Title, strings.TrimSpace(m.Summary)))
	w("* **Identifier:** %s\n", identifier(currentType(m), m.Number))
	w("* **Document type:** %s\n", typeName(r, currentType(m)))
	if wg := workingGroupLink(r, m); wg != "" {
		w("* **Working group:** %s\n", wg)
	}
	if v := latestPublished(m); v != nil {
		w("* **Latest version:** %s, published %s\n", versionLink(m, v), v.Published)
	} else {
		w("* **Latest version:** none; every version has been withdrawn or superseded\n")
	}
	w("* **Permanent address:** <%s>\n", docURL(m.Shortname))
	if len(m.Obsoletes) > 0 {
		var s []string
		for _, o := range m.Obsoletes {
			s = append(s, fmt.Sprintf("[%s](%s)", o.ID, o.URL))
		}
		w("* **Obsoletes:** %s\n", joinList(s))
	}
	if len(m.Keywords) > 0 {
		w("* **Keywords:** %s\n", strings.Join(m.Keywords, ", "))
	}

	w("\n## Versions\n\n")
	w("| Version | Type | Status | Published |\n| --- | --- | --- | --- |\n")
	for i := len(m.Versions) - 1; i >= 0; i-- {
		v := &m.Versions[i]
		w("| %s | %s | %s | %s |\n", versionLink(m, v), v.Type, titleCase(v.Status), v.Published)
	}
	w("\nEach published version is final and never changes. Confirmed errors are corrected through an erratum or a corrigendum, published alongside the version it corrects, or through a new version.\n")

	if list := reviewsOf(s, m.Shortname); len(list) > 0 {
		w("\n## Public Reviews\n\n")
		w("%s", stagesHTML(s, m.Shortname))
		w("\nThe [public review history](%s/) lists every review of this document's drafts.\n", reviewsPath(m.Shortname))
	}

	if len(m.Implementations) > 0 {
		w("\n## Implementations\n\n")
		for _, im := range m.Implementations {
			w("* %s: <%s>\n", im.Language, im.URL)
		}
	}

	w("\n## Machine Readable Data\n\n")
	w("The details on this page come from [metadata.yaml](%s). Every OSTERA publication is listed in [catalog.json](/catalog.json).\n\n", path(m, "metadata.yaml"))
	w("%s\n", githubLink(d.Dir))
	return b.String()
}

// ---------- version landing page ----------

func versionPage(r *Registry, d Document, v *Version) string {
	m := d.Meta
	dir := versionDir(v.Version)
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }

	w("%s", frontMatter(fmt.Sprintf("%s, Version %s", identifier(v.Type, m.Number), v.Version), m.Title))
	switch v.Status {
	case "superseded":
		if n := newerPublished(m, v); n != nil {
			w("> **This version has been superseded by %s.**\n\n", versionLink(m, n))
		} else {
			w("> **This version has been superseded.** See the [document page](%s/) for the current version.\n\n", path(m))
		}
	case "withdrawn":
		w("> **This version has been withdrawn.** See the [document page](%s/) for its other versions.\n\n", path(m))
	}

	w("* **Document:** [%s](%s/)\n", m.Title, path(m))
	w("* **Status:** %s\n", titleCase(v.Status))
	w("* **Published:** %s\n", v.Published)
	w("* **Document type:** %s\n", typeName(r, v.Type))
	if wg := workingGroupLink(r, m); wg != "" {
		w("* **Working group:** %s\n", wg)
	}
	if len(v.Authors) > 0 {
		w("* **Authors:** %s\n", people(v.Authors))
	}
	if len(v.Editors) > 0 {
		w("* **Editors:** %s\n", people(v.Editors))
	}
	if len(v.Incorporates) > 0 {
		w("* **Incorporates:** %s\n", joinList(v.Incorporates))
	}
	w("* **Permanent address:** <%s/%s/>\n", strings.TrimSuffix(docURL(m.Shortname), "/"), dir)

	w("\n## Files\n\n")
	for _, lang := range v.Languages {
		for _, f := range v.Formats {
			name := artifactName(m, v, "", 0, lang, f)
			note := ""
			if lang == m.AuthoritativeLanguage && f == m.AuthoritativeFormat {
				note = " (authoritative)"
			}
			w("* [%s](%s)%s: `%s`\n", fileLabel(lang, f), path(m, dir, name), note, name)
		}
	}
	w("* [%s](%s): checksums for the files above\n", sumsFile, path(m, dir, sumsFile))
	if len(v.Languages)*len(v.Formats) > 1 {
		w("\nIf the files differ, the %s is authoritative.\n", fileLabel(m.AuthoritativeLanguage, m.AuthoritativeFormat))
	}

	if len(v.Corrections) > 0 {
		w("\n## Corrections\n\n")
		for _, c := range v.Corrections {
			var files []string
			for _, lang := range c.Languages {
				for _, f := range c.Formats {
					files = append(files, fmt.Sprintf("[%s](%s)", fileLabel(lang, f), path(m, "corrections", artifactName(m, v, c.Kind, c.Sequence, lang, f))))
				}
			}
			w("* %s %d, %s: %s\n", titleCase(c.Kind), c.Sequence, c.Date, joinList(files))
		}
		w("\nChecksums for the corrections are in [%s](%s).\n", sumsFile, path(m, "corrections", sumsFile))
	}

	w("\n## Verifying a File\n\n")
	w("Compute the SHA512 checksum of the downloaded file and compare it with the matching line in `%s`:\n\n", sumsFile)
	w("```\nshasum -a 512 %s\n```\n\n", artifactName(m, v, "", 0, m.AuthoritativeLanguage, m.AuthoritativeFormat))
	w("%s\n", githubLink(d.Dir+"/"+dir))
	return b.String()
}

// ---------- generated sections of hand written pages ----------

func homeSection(s *site) string {
	r, docs := s.reg, s.docs
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }
	w("## Documents by Working Group\n\n")
	if len(docs) == 0 {
		w("No documents have been published yet.\n")
		return b.String()
	}

	// Working Groups in name order, then documents developed by the
	// Association, which have no Working Group.
	byGroup := map[string][]Document{}
	for _, d := range docs {
		byGroup[d.Meta.WorkingGroup] = append(byGroup[d.Meta.WorkingGroup], d)
	}
	groups := sortedKeys(byGroup)
	sort.SliceStable(groups, func(i, j int) bool {
		if groups[i] == "" || groups[j] == "" {
			return groups[j] == ""
		}
		return r.WorkingGroups[groups[i]].Name < r.WorkingGroups[groups[j]].Name
	})
	for _, g := range groups {
		if g == "" {
			w("### OSTERA Policies and Processes\n\n")
		} else {
			w("### %s\n\n", workingGroupLink(r, byGroup[g][0].Meta))
		}
		w("| Document | Identifier | Latest Version |\n| --- | --- | --- |\n")
		for _, d := range byGroup[g] {
			m := d.Meta
			latest := "Withdrawn"
			if v := latestPublished(m); v != nil {
				latest = fmt.Sprintf("%s (%s)", versionLink(m, v), v.Published)
			}
			w("| [%s](%s/) | %s | %s |\n", cell(m.Title), path(m), identifier(currentType(m), m.Number), latest)
		}
		w("\n")
	}
	return b.String()
}

func typesSection(s *site) string {
	r := s.reg
	var b strings.Builder
	b.WriteString("| Code | Document Type | Patent Licensing Obligations |\n| --- | --- | --- |\n")
	for _, code := range orderedTypes(r) {
		t := r.Types[code]
		fmt.Fprintf(&b, "| %s | %s | %s |\n", code, cell(t.Name), patentText[t.Track])
	}
	return b.String()
}

// ---------- catalog.json ----------

type catalog struct {
	SchemaVersion int          `json:"schema_version"`
	Site          string       `json:"site"`
	Documents     []catalogDoc `json:"documents"`
}

type catalogDoc struct {
	Number                int              `json:"number"`
	Identifier            string           `json:"identifier"`
	Shortname             string           `json:"shortname"`
	Title                 string           `json:"title"`
	Type                  string           `json:"type"`
	WorkingGroup          string           `json:"working_group,omitempty"`
	WorkingGroupName      string           `json:"working_group_name,omitempty"`
	AuthoritativeLanguage string           `json:"authoritative_language"`
	AuthoritativeFormat   string           `json:"authoritative_format"`
	URL                   string           `json:"url"`
	Metadata              string           `json:"metadata"`
	LatestVersion         string           `json:"latest_version,omitempty"`
	Versions              []catalogVersion `json:"versions"`
}

type catalogVersion struct {
	Version     string              `json:"version"`
	Type        string              `json:"type"`
	Status      string              `json:"status"`
	Published   string              `json:"published"`
	URL         string              `json:"url"`
	Files       []string            `json:"files"`
	Checksums   string              `json:"checksums"`
	Corrections []catalogCorrection `json:"corrections"`
}

type catalogCorrection struct {
	Kind     string   `json:"kind"`
	Sequence int      `json:"sequence"`
	Date     string   `json:"date"`
	Files    []string `json:"files"`
}

func catalogJSON(r *Registry, docs []Document) ([]byte, error) {
	cat := catalog{SchemaVersion: 1, Site: siteURL + "/", Documents: []catalogDoc{}}
	for _, d := range docs {
		m := d.Meta
		cd := catalogDoc{
			Number:                m.Number,
			Identifier:            identifier(currentType(m), m.Number),
			Shortname:             m.Shortname,
			Title:                 m.Title,
			Type:                  currentType(m),
			WorkingGroup:          m.WorkingGroup,
			AuthoritativeLanguage: m.AuthoritativeLanguage,
			AuthoritativeFormat:   m.AuthoritativeFormat,
			URL:                   docURL(m.Shortname),
			Metadata:              siteURL + path(m, "metadata.yaml"),
			Versions:              []catalogVersion{},
		}
		if wg, ok := r.WorkingGroups[m.WorkingGroup]; ok {
			cd.WorkingGroupName = wg.Name
		}
		if v := latestPublished(m); v != nil {
			cd.LatestVersion = v.Version
		}
		for i := range m.Versions {
			v := &m.Versions[i]
			dir := versionDir(v.Version)
			cv := catalogVersion{
				Version: v.Version, Type: v.Type, Status: v.Status, Published: v.Published,
				URL:         siteURL + path(m, dir) + "/",
				Files:       []string{},
				Checksums:   siteURL + path(m, dir, sumsFile),
				Corrections: []catalogCorrection{},
			}
			for _, name := range expectedVersionFiles(m, v) {
				cv.Files = append(cv.Files, siteURL+path(m, dir, name))
			}
			for _, c := range v.Corrections {
				cc := catalogCorrection{Kind: c.Kind, Sequence: c.Sequence, Date: c.Date, Files: []string{}}
				for _, lang := range c.Languages {
					for _, f := range c.Formats {
						cc.Files = append(cc.Files, siteURL+path(m, "corrections", artifactName(m, v, c.Kind, c.Sequence, lang, f)))
					}
				}
				cv.Corrections = append(cv.Corrections, cc)
			}
			cd.Versions = append(cd.Versions, cv)
		}
		cat.Documents = append(cat.Documents, cd)
	}
	data, err := json.MarshalIndent(cat, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(data, '\n'), nil
}
